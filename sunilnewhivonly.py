Lambda = 151002   # annual recruitment into susceptible population
mu     = 0.0012   # natural background mortality rate
TOTAL_INIT = 96565   # total infected at baseline year (Ih0 + Ia0)
S0         = 1250345700

# ── ODE system ───────────────────────────────────────────────────────────────
def seir_model(y, t, beta_h, kappa, delta_h):
    """
    Compartments:
      S  – Susceptible
      Ih – HIV-positive (not yet AIDS)
      Ia – AIDS stage
    """
    S, Ih, Ia = y
    N = S + Ih + Ia

    lambda_h = beta_h * (Ih + Ia) / N        # force of infection

    dSdt  = Lambda - (lambda_h + mu) * S
    dIhdt = lambda_h * S - (kappa  + mu) * Ih
    dIadt = kappa  * Ih  - (delta_h + mu) * Ia

    return [dSdt, dIhdt, dIadt]


# ── Objective function (reparameterised) ─────────────────────────────────────
def objective(params, t, observed):
    """
    Free parameters: [eps, kappa, delta_h, frac]
      eps     : R0 excess above 1  (R0 = 1 + eps,  eps > 0)
      kappa   : progression rate HIV → AIDS
      delta_h : AIDS-related mortality / removal rate
      frac    : fraction of TOTAL_INIT assigned to Ih0  (rest goes to Ia0)
    """
    eps, kappa, delta_h, frac = params

    # Recover beta_h so that R0 = 1 + eps  (always > 1)
    beta_h = (kappa + mu) * (1.0 + eps)

    Ih0 = frac         * TOTAL_INIT
    Ia0 = (1.0 - frac) * TOTAL_INIT

    y0 = [S0, Ih0, Ia0]

    try:
        sol = odeint(seir_model, y0, t,
                     args=(beta_h, kappa, delta_h),
                     mxstep=5000, full_output=False)
        predicted = sol[:, 1] + sol[:, 2]          # Ih + Ia at each time point
        sse = np.sum((observed - predicted) ** 2)
    except Exception:
        sse = 1e18

    return sse


