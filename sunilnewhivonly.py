    beta_h, kappa, delta_h, Ih0, Ia0 = params

    S0 = 1250345700
    y0 = [S0, Ih0, Ia0]

    try:
        sol = odeint(seir_model, y0, t, args=(beta_h, kappa, delta_h),
                     mxstep=5000, full_output=False)
        predicted = sol[:, 1] + sol[:, 2]   # Ih + Ia at each time point
        sse = np.sum((observed_combined - predicted) ** 2)
    except Exception:
        sse = 1e18

    return sse


