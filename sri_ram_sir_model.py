def state_at(year):
    return sol.sol(year)

def annual_flow_integral(year, flow_fn, n=200):
    """Integrate a flow-rate function (per-year rate) over one calendar year
    using the dense ODE solution, via Simpson's rule on a fine grid."""
    ts = np.linspace(year, year + 1, n)
    ys = sol.sol(ts)
    vals = np.array([flow_fn(ts[i], ys[:, i]) for i in range(n)])
    return np.trapezoid(vals, ts)

