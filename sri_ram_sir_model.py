"""
Reimplementation of the compartmental TB model in:
Mandal S, Rao R, Joshi R. "Estimating the Burden of Tuberculosis in India:
A Modelling Study." Indian J Community Med 2023;48:436-42.

This version adds an UNCERTAINTY BAND for the model outputs, so the
"Model" points in the Figure 2 plot get a lo/mid/hi just like "Data" does.

METHOD USED (read this before trusting the numbers):
  The paper gets its Model lo/mid/hi from full Bayesian MCMC calibration --
  every uncertain parameter is jointly updated against ALL calibration
  targets at once, and the reported 95% CrI is the 2.5th/97.5th percentile
  of that joint posterior.

  Reproducing that exactly requires writing a log-posterior (beta /
  log-normal likelihoods against each Data target) and running an
  MCMC sampler (e.g. emcee, or a hand-rolled Metropolis-Hastings) -- that
  is a bigger undertaking than what's below.

  What THIS script does instead is simpler and faster to run: it takes
  the marginal 95% CI already reported for each parameter in Table S1,
  treats each one as an independent Normal distribution, draws N random
  parameter sets from those independent distributions ("Monte Carlo
  forward uncertainty propagation"), runs the full ODE model once per
  draw, and reports the 2.5th/50th/97.5th percentiles of the resulting
  simulated outputs as Model lo/mid/hi.

  This is NOT the same as MCMC calibration -- it does not use the Data
  targets to constrain the parameter draws at all, and it ignores the
  correlations between parameters that a joint posterior would have.
  It will therefore give a wider and differently-centred band than the
  paper's. But it is the correct, standard way to answer "how much does
  my model output vary given the parameter uncertainty I was told about",
  and it's the natural stepping stone toward full MCMC (see the bottom
  of this file for how that would differ in code structure).
"""

