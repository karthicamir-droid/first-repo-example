# ---------------------------------------------------------------------------
# 1. PARAMETERS  (posterior medians, Table S1)
# ---------------------------------------------------------------------------
P = dict(
    beta      = 4.4,     # rate-of-transmission (Table S1 calls it "b")
    mu        = 1/70,    # background mortality (and birth rate, to hold N~1)
    u         = 0.07,    # Lf -> I progression
    v         = 0.85,    # Lf -> Ls stabilisation
    w         = 0.0035,  # Ls -> I reactivation
    c         = 0.031,   # LTBI self-clearance (Lf,Ls -> U)
    sigma     = 0.17,    # self-cure from active TB
    muTB      = 0.07,    # TB mortality, untreated
    muTB_pu   = 0.103,   # TB mortality, on public treatment
    muTB_pr   = 0.051,   # TB mortality, on private treatment
    h         = 0.38,    # protection from reinfection (recovered classes)
    rho_lo    = 0.083,   # relapse rate, low-risk
    rho_hi    = 0.14,    # relapse rate, high-risk
    rho       = 0.0015,  # relapse rate, long-term stabilised
    s         = 0.5,     # stabilisation rate Rhi/Rlo -> R
    delta     = 52,      # rate of "offering" diagnosis once presented (~weekly)
    pDx_pu    = 0.67,    # prob. successful public dx+tx initiation per visit
    pDx_pr    = 0.64,    # prob. successful private dx+tx initiation per visit
    tau       = 2.0,     # treatment completion rate (~6 month course)
    eps_pu    = 0.52,    # treatment interruption rate, public
    eps_pr    = 2.2,     # treatment interruption rate, private
    gamma_tilde = 4.9,   # careseeking rate, 2nd+ attempts (const 2011->2020)
    # time-varying pieces (linear 2011->2020, then held flat):
    gamma_2011 = 0.30,
    gamma_2020 = 0.55,
    p_2011     = 0.50,
    p_2020     = 0.60,
)

T0, T1 = 2011.0, 2020.0  # window over which gamma(t), p(t) ramp linearly


def linear_ramp(t, y0, y1, t0=T0, t1=T1):
    """Linear interpolation from y0 at t0 to y1 at t1; flat before/after."""
    if t <= t0:
        return y0
    if t >= t1:
        return y1
    return y0 + (y1 - y0) * (t - t0) / (t1 - t0)


def beta_t(t, beta_base):
    """
    50% reduction in transmission during:
      - national lockdown: Apr-Jul 2020
      - delta wave:        May-Sep 2021
    (as stated in the Methods / Fig S3 discussion)
    """
    if (2020 + 3/12 <= t <= 2020 + 7/12) or (2021 + 4/12 <= t <= 2021 + 9/12):
        return 0.5 * beta_base
    return beta_base


def a_t(t):
    """
    Active-case-finding rate. The paper does not give a closed-form a(t);
    it is calibrated against annual ACF notification counts (Table:
    26,781 in 2017 ... 73,772 in 2021). Left at 0 here -- see README notes
    at the bottom of this file for how to extend it.
    """
    return 0.0


def rhs(t, y, P):
    U, Lf, Ls, I, Dpu, Dpr, E, Tpu, Tpr, Rlo, Rhi, R = y

    gamma = linear_ramp(t, P['gamma_2011'], P['gamma_2020'])
    p     = linear_ramp(t, P['p_2011'],     P['p_2020'])
    beta  = beta_t(t, P['beta'])
    gt    = P['gamma_tilde']
    a     = a_t(t)
    mu    = P['mu']

    lam = beta * (I + E + Dpr + Dpu)                       # force of infection
    b   = mu                                                # birth = death -> N const

    dU   = b - (lam + mu) * U + P['c'] * (Lf + Ls)
    dLf  = lam * (U + (1 - P['h']) * (Rhi + Rlo + R)) \
           - (P['u'] + P['v'] + P['c'] + mu) * Lf
    dLs  = P['v'] * Lf - (P['w'] + P['c'] + mu) * Ls
    dI   = P['u'] * Lf + P['w'] * Ls \
           + (P['rho_hi'] * Rhi + P['rho_lo'] * Rlo + P['rho'] * R) \
           - (gamma + P['muTB'] + P['sigma'] + a + mu) * I
    dDpu = p * gamma * I + p * gt * E \
           - (P['delta'] + P['muTB'] + P['sigma'] + mu) * Dpu
    dDpr = (1 - p) * gamma * I + (1 - p) * gt * E \
           - (P['delta'] + P['muTB'] + P['sigma'] + mu) * Dpr
    dE   = P['delta'] * (1 - P['pDx_pu']) * Dpu \
           + P['delta'] * (1 - P['pDx_pr']) * Dpr \
           - (P['muTB'] + P['sigma'] + gt + mu) * E
    dTpu = P['delta'] * P['pDx_pu'] * Dpu + a * I \
           - (P['tau'] + P['muTB_pu'] + P['eps_pu'] + mu) * Tpu
    dTpr = P['delta'] * P['pDx_pr'] * Dpr \
           - (P['tau'] + P['muTB_pr'] + P['eps_pr'] + mu) * Tpr
    dRlo = P['tau'] * (Tpu + Tpr) \
           - ((1 - P['h']) * lam + P['rho_lo'] + mu + P['s']) * Rlo
    dRhi = P['eps_pu'] * Tpu + P['eps_pr'] * Tpr \
           - ((1 - P['h']) * lam + P['rho_hi'] + mu + P['s']) * Rhi
    dR   = P['s'] * (Rlo + Rhi) - ((1 - P['h']) * lam + P['rho'] + mu) * R

    return [dU, dLf, dLs, dI, dDpu, dDpr, dE, dTpu, dTpr, dRlo, dRhi, dR]


