"""
Reproduce: "Modelling disruptions, 2020-2021" -- India monthly TB notifications,
public and private sectors, with modelled baseline vs modelled disruption.

METHOD SOURCE (verbatim structure, paraphrased description):
WHO Global Tuberculosis Report 2021, featured topic "COVID-19, TB and India"
  https://www.who.int/publications/digital/global-tuberculosis-report-2021/featured-topics/covid-19-tb-india
This describes exactly this modelling approach: a TB transmission model's
detection rate is modified by a time-varying factor k(t), fitted monthly to
match observed Nikshay notification data, separately for public and private
sectors. The "baseline" is the same model run WITHOUT the k(t) adjustment
(i.e. assuming pre-2020 trends continued); the "disruption" line is the
model WITH k(t) fitted to the data, with a 95% Bayesian credible interval.

BASE DATA SOURCE:
  Nikshay (India's national TB case-based surveillance system), monthly
  notification counts by public/private sector:
    https://reports.nikshay.in/Reports/TBNotification
    (interactive dashboard -- select a date range, split by sector, and use
     "Download Excel"; no static bulk CSV endpoint is exposed)
  Also tabulated annually in Central TB Division's "India TB Report" series:
    https://tbcindia.gov.in

  Cross-check anchor (WHO GTB2021 Annex 1, Table A1):
    2019 annual notification rate, public sector:  127 per 100,000
    2019 annual notification rate, private sector:  50 per 100,000

PART 1 below builds an illustrative version from synthetic monthly data
shaped to match the anchor values and the two known disruption windows
(lockdown Apr-Jul 2020, Delta wave Apr-May 2021). It demonstrates the
modelling method (baseline fit + smoothed disruption curve + credible band)
end to end, but the exact data points are NOT the real Nikshay series.

PART 2 shows how to plug in the REAL monthly counts once you've pulled them
from the Nikshay dashboard or an India TB Report annex.
"""

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from scipy.optimize import curve_fit
from scipy.ndimage import gaussian_filter1d

rng = np.random.default_rng(7)

# ---------------------------------------------------------------------------
# PART 1: BUILD ILLUSTRATIVE MONTHLY DATA (shaped like the real pattern)
# ---------------------------------------------------------------------------
months = pd.date_range('2019-01-01', '2022-05-01', freq='MS')
n = len(months)
t = np.arange(n)  # months since Jan 2019

def make_series(annual_rate_2019, lockdown_drop, delta_drop, noise_sd, seed):
    """annual_rate_2019: WHO Table A1 anchor (per 100,000/year) -> /12 for monthly.
    lockdown_drop / delta_drop: fractional drop at the trough of each disruption."""
    local_rng = np.random.default_rng(seed)
    monthly_base = annual_rate_2019 / 12
    # gentle pre-existing downward trend, consistent with the model's baseline
    trend = monthly_base * (1 - 0.01 * t)

    disruption = np.ones(n)
    for i, m in enumerate(months):
        if pd.Timestamp('2020-04-01') <= m <= pd.Timestamp('2020-07-01'):
            # dip and partial recovery within the window
            frac = (m - pd.Timestamp('2020-04-01')).days / 90
            disruption[i] = 1 - lockdown_drop * (1 - 0.6 * frac)
        elif pd.Timestamp('2021-04-01') <= m <= pd.Timestamp('2021-06-01'):
            frac = (m - pd.Timestamp('2021-04-01')).days / 60
            disruption[i] = 1 - delta_drop * (1 - 0.6 * frac)

    data = trend * disruption + local_rng.normal(0, noise_sd, n)
    return np.clip(data, 0.1, None)

public_data = make_series(annual_rate_2019=127, lockdown_drop=0.58,
                           delta_drop=0.62, noise_sd=0.35, seed=1)
private_data = make_series(annual_rate_2019=50, lockdown_drop=0.65,
                            delta_drop=0.45, noise_sd=0.25, seed=2)


# ---------------------------------------------------------------------------
# PART 2: THE MODELLING METHOD -- baseline fit + smoothed disruption curve
# ---------------------------------------------------------------------------
def fit_baseline(t, y, pre_period_mask):
    """Linear fit to PRE-DISRUPTION data only -- this is the model's
    'no-disruption' counterfactual, extrapolated across the full period."""
    coeffs = np.polyfit(t[pre_period_mask], y[pre_period_mask], deg=1)
    return np.polyval(coeffs, t)


def fit_disruption(t, y, smooth_sigma=1.2, n_boot=300):
    """Smoothed fit to ALL data (captures the dips), analogous to the
    model's k(t)-adjusted trajectory. A bootstrap over residuals gives an
    approximate credible band -- WHO's actual band comes from full Bayesian
    MCMC on the transmission model; this is a simpler stand-in with the same
    qualitative behaviour (still uses real Gaussian smoothing, not fabricated
    bounds)."""
    smoothed = gaussian_filter1d(y, sigma=smooth_sigma)
    resid = y - smoothed
    resid_sd = np.std(resid)

    boot = np.zeros((n_boot, len(t)))
    for b in range(n_boot):
        noisy = smoothed + rng.normal(0, resid_sd, len(t))
        boot[b] = gaussian_filter1d(noisy, sigma=smooth_sigma)

    lo = np.percentile(boot, 2.5, axis=0)
    hi = np.percentile(boot, 97.5, axis=0)
    return smoothed, lo, hi


pre_mask = months < pd.Timestamp('2020-02-01')

pub_baseline = fit_baseline(t, public_data, pre_mask)
pub_disrupt, pub_lo, pub_hi = fit_disruption(t, public_data)

priv_baseline = fit_baseline(t, private_data, pre_mask)
priv_disrupt, priv_lo, priv_hi = fit_disruption(t, private_data)


