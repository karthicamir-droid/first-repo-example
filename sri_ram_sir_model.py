def sample_params():
    """Draw one random parameter set from the specs above."""
    P = {}
    for name, (mid, lo, hi, dist, clo, chi) in PARAM_SPECS.items():
        if dist == 'fixed':
            P[name] = mid
        else:  # normal, from 95% CI
            sd = (hi - lo) / (2 * 1.96)
            val = rng.normal(mid, sd)
            if clo is not None:
                val = max(val, clo)
            if chi is not None:
                val = min(val, chi)
            P[name] = val
    return P


